/**
 * @jest-environment node
 *
 * Framework coverage report (docs/taint/framework-coverage.md), generated from what is actually in the repository:
 * the detection registry, the *FrameworkSources suites' case lists, the benchmark baselines and the CWE map.
 *
 * A framework is "supported" only when at least one vulnerable AND one safe test case names it; a framework with
 * neither is listed as unverified, so the report cannot claim more than the tests prove. The test fails when the
 * checked-in report is stale -- regenerate with:  WRITE_REPORT=1 npx jest src/__tests__/lib/frameworkCoverageReport.test.ts
 */
import fs from "fs";
import path from "path";
import { FRAMEWORKS, type FwLang } from "@/lib/taint/frameworks";
import { INDICATOR_CWE_MAP } from "@/lib/cweMap";
import { DATA_FLOW_LANGUAGES } from "@/lib/ruleLanguages";

const ROOT = path.resolve(__dirname, "../../..");
const SUITES: Array<{ file: string; lang: string }> = [
  { file: "jsFrameworkSources", lang: "javascript" }, { file: "tsFrameworkSources", lang: "typescript" }, { file: "pyFrameworkSources", lang: "python" },
  { file: "javaFrameworkSources", lang: "java" }, { file: "goFrameworkSources", lang: "go" }, { file: "csFrameworkSources", lang: "csharp" },
  { file: "phpFrameworkSources", lang: "php" }, { file: "rubyFrameworkSources", lang: "ruby" }, { file: "kotlinFrameworkSources", lang: "kotlin" },
  { file: "rustFrameworkSources", lang: "rust" }, { file: "cppFrameworkSources", lang: "cpp" },
  { file: "frameworkGaps", lang: "mixed" },
];
const LANG_OF: Record<FwLang, string[]> = {
  js: ["javascript", "typescript"], py: ["python"], java: ["java"], kt: ["kotlin"], go: ["go"], cs: ["csharp"], php: ["php"], rb: ["ruby"], rs: ["rust"], cpp: ["cpp"],
};
/** Words a test-case name uses for a framework, where the id's first token is not it. */
const KEYWORDS: Record<string, string[]> = {
  "spring-boot": ["spring"], "jax-rs": ["jax", "jaxrs", "quarkus", "jersey"], "gorilla-mux": ["gorilla", "mux"], "net-http": ["net/http", "nethttp", "stdlib"],
  aspnetcore: ["asp", "mvc", "razor", "blazor", "minimal api", "controller"], "entity-framework": ["entity", "efcore", "ef core", "ef6", "fromsql", "executesql"],
  "actix-web": ["actix"], "sea-orm": ["sea", "seaorm"], "boost-asio-beast": ["boost", "asio", "beast"], "apache-httpd": ["apache", "httpd"],
  hibernate: ["hibernate", "jpa", "entitymanager", "createnativequery"], nextjs: ["next"], nestjs: ["nest"], sqlalchemy: ["sqlalchemy", "text("], sqlite3: ["sqlite"],
  "http4k": ["http4k"], exposed: ["exposed"], libcurl: ["curl"], laravel: ["laravel", "eloquent", "blade"], rails: ["rails", "activerecord", "erb"], django: ["django"],
  wordpress: ["wordpress", "wpdb", "wp_"], symfony: ["symfony", "twig"], codeigniter: ["codeigniter", "ci_"], doctrine: ["doctrine"], jinja2: ["jinja"],
};
const keywordsOf = (id: string) => KEYWORDS[id] ?? [id.split("-")[0]];

interface Case { name: string; negative: boolean; lang: string }

/** `["name", ...]` rows of a suite, negative when they sit in an array named safe/negative/clean, are tagged "!rule" / "SAFE", or start the name with "neg". */
function casesOf(suite: { file: string; lang: string }): Case[] {
  const text = fs.readFileSync(path.join(__dirname, `${suite.file}.test.ts`), "utf8");
  const out: Case[] = [];
  let negativeArray = false;
  for (const line of text.split(/\r?\n/)) {
    const decl = /^\s*(?:export\s+)?const\s+(\w+)\s*(?::[^=]+)?=\s*\[/.exec(line);
    if (decl) negativeArray = /safe|neg|clean|benign/i.test(decl[1]);
    else if (/^\s*\];/.test(line)) negativeArray = false;
    const m = /^\s*\[\s*"((?:[^"\\]|\\.)+)"\s*,/.exec(line);
    if (!m) continue;
    const negative = negativeArray || /,\s*"!\w/.test(line) || /,\s*"SAFE"/.test(line) || /^neg\b/i.test(m[1]) || /\bsafe\b/i.test(m[1]) && !/\bunsafe\b/i.test(m[1]);
    out.push({ name: m[1], negative, lang: suite.lang });
  }
  return out;
}

function buildReport(): string {
  const cases = SUITES.flatMap(casesOf);
  const lines: string[] = [];
  const P = (s = "") => lines.push(s);

  P("# Framework coverage report");
  P();
  P("Generated by `src/__tests__/lib/frameworkCoverageReport.test.ts` -- do not edit by hand.");
  P("Regenerate: `WRITE_REPORT=1 npx jest src/__tests__/lib/frameworkCoverageReport.test.ts`.");
  P();
  P("A framework is **supported** only when at least one vulnerable and one safe test case names it. Matching is by case name");
  P("(`tests mention`), so a framework whose cases are named after the API (`createNativeQuery`) rather than the framework can read as");
  P("unverified here while being tested -- the count is a floor, not a ceiling.");
  P();

  // ── 1. registry
  P("## 1. Detection registry");
  P();
  P(`${FRAMEWORKS.length} frameworks / ORMs / clients / template engines (\`src/lib/taint/frameworks.ts\`), detected from manifests (with versions), package-specific imports, convention files and paired weak signals.`);
  P();
  P("| Language | Frameworks |");
  P("|---|---|");
  for (const lang of ["js", "py", "java", "kt", "go", "cs", "php", "rb", "rs", "cpp"] as FwLang[]) {
    P(`| ${LANG_OF[lang].join(" / ")} | ${FRAMEWORKS.filter(f => f.langs.includes(lang)).map(f => f.name).join(", ")} |`);
  }
  P();

  // ── 2. per-framework coverage
  P("## 2. Per-framework test coverage");
  P();
  P("| Framework | Language | Kind | Vulnerable cases | Safe cases | Status |");
  P("|---|---|---|---:|---:|---|");
  let supported = 0, unverified = 0;
  for (const fw of FRAMEWORKS) {
    const langs = fw.langs.flatMap(l => LANG_OF[l]);
    const kws = keywordsOf(fw.id).map(k => k.toLowerCase());
    const mine = cases.filter(c => (langs.includes(c.lang) || c.lang === "mixed") && kws.some(k => c.name.toLowerCase().includes(k)));
    const vuln = mine.filter(c => !c.negative).length, safe = mine.filter(c => c.negative).length;
    const status = vuln > 0 && safe > 0 ? "supported" : vuln > 0 ? "vulnerable-only (add a safe case)" : "unverified";
    if (status === "supported") supported++; else unverified++;
    P(`| ${fw.name} | ${langs.join("/")} | ${fw.kind} | ${vuln} | ${safe} | ${status} |`);
  }
  P();
  P(`**${supported} supported, ${unverified} not yet proven by name-matched tests** of ${FRAMEWORKS.length}.`);
  P();

  // ── 3. suite sizes
  P("## 3. Framework test suites (regression corpus, in-sample)");
  P();
  P("| Suite | Vulnerable | Safe |");
  P("|---|---:|---:|");
  let tv = 0, ts = 0;
  for (const s of SUITES) {
    const mine = cases.filter(c => c.lang === s.lang);
    const v = mine.filter(c => !c.negative).length, n = mine.length - v;
    tv += v; ts += n;
    P(`| ${s.file} | ${v} | ${n} |`);
  }
  P(`| **total** | **${tv}** | **${ts}** |`);
  P();
  P("These suites were written alongside the engines and all pass, so on them recall and precision are 100% by construction: they pin");
  P("behaviour (no regression), they do not estimate accuracy on unseen code. Cases whose files are cross-file objects (Java, parts of");
  P("PHP) are not in these counts; see section 4.");
  P();

  // ── 4. independent-ish measurements
  const bench = (name: string) => JSON.parse(fs.readFileSync(path.join(ROOT, "src/__tests__/benchmarks", name), "utf8"));
  P("## 4. Benchmarks");
  P();
  P("### Hard benchmark programs (one real vulnerability per case)");
  P();
  P("| Language | Cases | Cases with a finding | Recall | AST data-flow findings |");
  P("|---|---:|---:|---:|---:|");
  const hard = bench("baseline.json") as Record<string, { totalCases: number; casesWithFinding: number; astOnlyFindingCount: number }>;
  for (const [lang, v] of Object.entries(hard)) P(`| ${lang} | ${v.totalCases} | ${v.casesWithFinding} | ${(100 * v.casesWithFinding / v.totalCases).toFixed(0)}% | ${v.astOnlyFindingCount} |`);
  P();
  P("Recall only: the benchmark programs contain vulnerable cases, so it measures what is found, not what is wrongly reported.");
  P();
  const cf = bench("crossFile/crossFileBaseline.json") as { byLanguage: Record<string, unknown>; cases: Record<string, unknown> | unknown[] };
  const ip = bench("interprocedural/interproceduralBaseline.json") as Record<string, unknown>;
  P(`### Cross-file and interprocedural`);
  P();
  P(`- Cross-file baseline: ${Array.isArray(cf.cases) ? cf.cases.length : Object.keys(cf.cases).length} cases across ${Object.keys(cf.byLanguage).length} languages (\`benchmarks/crossFile\`).`);
  P(`- Interprocedural baseline: ${Object.keys(ip).length} cases (\`benchmarks/interprocedural\`).`);
  P();
  P("### Precision / recall mini-benchmark (`benchmarks/engineMetrics.test.ts`)");
  P();
  P("30 vulnerable + 30 safe twins over 10 languages: TP 30, FP 0, FN 0, TN 30 (precision 1.00, recall 1.00). Six cases per language is a");
  P("regression guard, not a measurement: it cannot reveal a false-positive rate. A real precision/recall figure needs a large labelled");
  P("external corpus (the open item recorded under \"large per-language benchmarks\").");
  P();

  // ── 5. CWE mapping
  P("## 5. CWE mapping of data-flow rules");
  P();
  P("| Rule | CWE | Languages with a data-flow engine for it |");
  P("|---|---|---|");
  const langsOf = new Map<string, string[]>();
  for (const { language, ids } of DATA_FLOW_LANGUAGES) for (const id of ids) langsOf.set(id, [...(langsOf.get(id) ?? []), language]);
  for (const id of [...langsOf.keys()].sort()) {
    const cwe = INDICATOR_CWE_MAP[id];
    P(`| ${id} | ${cwe ? `${cwe.id} ${cwe.title}` : "(unmapped)"} | ${langsOf.get(id)!.join(", ")} |`);
  }
  P();

  // ── 6. limits
  P("## 6. Known limits");
  P();
  P("- Detection reports what a repository uses; the language engines still gate their framework models on their own imports. The registry does not yet feed them.");
  P("- Template files (Razor, Blade, Twig, ERB) are not parsed by the AST engines; their findings come from the regex layer.");
  P("- A missing CSRF token or authorization check cannot be told apart from middleware installed in another file; only explicit \"switched off\" patterns are reported.");
  P("- Sanitizers clear only the sink classes they neutralise (`taint/sanitizers.ts`); validation (a bound or allow-list check) clears through guards, not by name.");
  P();
  return lines.join("\n") + "\n";
}

const DOC = path.join(ROOT, "docs/taint/framework-coverage.md");

describe("framework coverage report", () => {
  const report = buildReport();

  it("never claims support without a vulnerable and a safe case", () => {
    for (const row of report.split("\n").filter(l => /\| supported \|$/.test(l))) {
      const cols = row.split("|").map(s => s.trim());
      expect(Number(cols[4])).toBeGreaterThan(0);
      expect(Number(cols[5])).toBeGreaterThan(0);
    }
  });

  it("classifies every case list it reads", () => {
    for (const s of SUITES) {
      const found = casesOf(s);
      // the object-shaped suites (Java cross-file) may have none; every other suite has both kinds
      if (found.length > 0) { expect(found.some(c => c.negative)).toBe(true); expect(found.some(c => !c.negative)).toBe(true); }
    }
  });

  it("is current (WRITE_REPORT=1 regenerates docs/taint/framework-coverage.md)", () => {
    if (process.env.WRITE_REPORT) { fs.writeFileSync(DOC, report); return; }
    expect(fs.existsSync(DOC)).toBe(true);
    expect(fs.readFileSync(DOC, "utf8").replace(/\r\n/g, "\n")).toBe(report);
  });
});
